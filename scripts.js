class TypeSelect extends HTMLElement {
    connectedCallback() {
        const select = this.querySelector('select');
        console.log(select);
        

        for (const key in data) {
            if (!Object.hasOwn(data, key)) continue;
            
            const option = document.createElement('OPTION');
            option.setAttribute('value', key);
            option.innerText = key;
            select.appendChild(option);
        }

        this.querySelector('button')?.addEventListener('click', () => {
            const value = this.querySelector('select')?.value;
            document.querySelector('#datatype').innerText = value;

            const props = data[value] ?? [];

            const list = document.querySelector('#result-list');
            list.innerHTML = '';

            for (let i = 0; i < props.length; i++) {
                const li = document.createElement('LI');
                li.innerText = props[i];

                list.appendChild(li);
            }

            document.querySelector('section').style.display = 'block';
        });
    }
}

window.customElements.define('type-select', TypeSelect);
